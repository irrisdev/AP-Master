using System.ComponentModel.DataAnnotations;

namespace AP_Master.Server.DTOs.Customer;

public class CustomerRequest
{
    [Required]
    [MinLength(2)]
    [MaxLength(100)]
    public string Name { get; set; } = string.Empty;

    [Required]
    [EmailAddress]
    [MaxLength(200)]
    public string Email { get; set; } = string.Empty;
}